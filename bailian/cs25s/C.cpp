// 有一天，大雄和他的伙伴们想穿越时空进行探险，可是时光机却出了一点故障，只能进行有限的时空穿越操作。大雄他们需要从现在出发，到达一个目标时间点进行探险，结束后再返回到现在，他们希望尽可能减少时光机的操作次数，你能帮助他们吗？


// 假设大雄和他的伙伴们出发的时间点（现在）为S（0 < S < 1,000,000），希望到达的时间点（目标）为T（0 < T < 1,000,000），已知时光机可以进行如下的时空穿越操作（X为正整数）：

// 可以从任意时刻X穿越到X+1或者X-1时刻

// 可以从任意时刻X穿越到X*2时刻

// 当X为偶数时，可以从X时刻穿越到X/2时刻


// 请问，大雄和他的伙伴们从S时刻出发，先到达T时刻，再回到S时刻最少需要多少次时空穿越操作？

// 输入
// 输入的第一个数是一个正整数N，表示测试数据一共有N组（0 < N < 20）。
// 之后有N行，每一行包含两个正整数S和T，表示出发和到达时间点。S≠T
// 输出
// 输出包括N行，每一行一个正整数，表示每组测试数据对应的最少时光机操作次数。
// 样例输入
// 2
// 5 17
// 4 8
// 样例输出
// 8
// 2

/*
 * ==================== 解题思路 ====================
 *
 * 【问题建模】
 * 把每个时间点看作图中的一个节点，每种操作看作一条边：
 *   - X -> X+1  (边权=1)
 *   - X -> X-1  (边权=1)
 *   - X -> X*2  (边权=1)
 *   - X -> X/2  (边权=1, 仅当X为偶数)
 *
 * 问题转化为：求从节点S到节点T的最短路径
 *
 * 【为什么用BFS？】
 * 因为所有边的权重都是1（每次操作都算1步），
 * BFS天然能找到边权为1的图中的最短路径。
 *
 * BFS的特点：按"层"扩展，先访问到的节点一定是最短路径
 *
 *        S (第0层)
 *       /|\
 *      / | \
 *     A  B  C  (第1层，距离=1)
 *    /|  |  |\
 *   D E  F  G H (第2层，距离=2)
 *
 * 【为什么返程=去程？】
 * 每个操作都有逆操作：
 *   +1 <-> -1
 *   *2 <-> /2
 * 所以去程的路径反过来走就是返程，步数相同。
 * 总步数 = 去程 * 2
 */

#include <iostream>
#include <queue>
#include <cstring>
using namespace std;

// 定义最大范围，因为可能需要先变大再变小
// 比如从5到17，可能走 5->10->20->19->18->17
const int MAXN = 2000001;

// dist[i] 表示从起点S到时间点i的最少步数
// -1 表示还没访问过
int dist[MAXN];
vector<int>(MAXN,-1);

/*
 * BFS求从start到target的最短步数
 *
 * 核心思想：
 * 1. 从起点开始，把起点放入队列
 * 2. 每次取出队头，尝试所有可能的操作（扩展邻居）
 * 3. 如果邻居没访问过，记录距离并入队
 * 4. 第一次到达终点时，就是最短距离
 */
int bfs(int start, int target) {
    // 特判：起点就是终点
    if (start == target) return 0;

    // 创建队列，用于BFS
    queue<int> q;

    // 起点入队，距离为0
    q.push(start);
    dist[start] = 0;

    // BFS主循环
    while (!q.empty()) {
        // 取出队头元素
        int cur = q.front();
        q.pop();

        // 当前点的距离
        int curDist = dist[cur];

        // ========== 尝试四种操作 ==========

        // 操作1: cur -> cur + 1
        int next1 = cur + 1;
        if (next1 < MAXN && dist[next1] == -1) {  // 在范围内且未访问
            dist[next1] = curDist + 1;             // 距离+1
            if (next1 == target) return dist[next1]; // 找到目标，直接返回
            q.push(next1);                         // 入队
        }

        // 操作2: cur -> cur - 1
        int next2 = cur - 1;
        if (next2 > 0 && dist[next2] == -1) {     // 时间点必须>0
            dist[next2] = curDist + 1;
            if (next2 == target) return dist[next2];
            q.push(next2);
        }

        // 操作3: cur -> cur * 2
        int next3 = cur * 2;
        if (next3 < MAXN && dist[next3] == -1) {
            dist[next3] = curDist + 1;
            if (next3 == target) return dist[next3];
            q.push(next3);
        }

        // 操作4: cur -> cur / 2 (仅当cur为偶数)
        if (cur % 2 == 0) {
            int next4 = cur / 2;
            if (next4 > 0 && dist[next4] == -1) {
                dist[next4] = curDist + 1;
                if (next4 == target) return dist[next4];
                q.push(next4);
            }
        }
    }

    // 理论上不会走到这里（题目保证有解）
    return -1;
}

int main() {
    int N;
    cin >> N;

    while (N--) {
        int S, T;
        cin >> S >> T;

        // 求去程的最短步数
        int goSteps = bfs(S, T);

        // 总步数 = 去程 + 返程 = 去程 * 2
        // （因为每个操作都有逆操作，返程步数等于去程）
        cout << goSteps * 2 << endl;
    }

    return 0;
}

